from math import isfinite

def replay_stopping(losses, patience, first_epoch=0):
    """Replay supplied validation observations; no training or real files are loaded."""
    if not losses or type(patience) is not int or patience < 1:
        raise ValueError('Need observations and positive integer patience')
    best_index = 0
    misses = 0
    trace = []
    stop_index = len(losses) - 1  # finite supplied observation budget
    for i, value in enumerate(losses):
        if not isfinite(value) or value < 0:
            raise ValueError('Observed MSE must be finite and nonnegative')
        if i == 0:
            decision = 'save initial best'
        elif value < losses[best_index]:
            best_index, misses = i, 0
            decision = 'save improved best'
        else:
            misses += 1
            decision = 'stop; select saved best' if misses >= patience else 'wait'
        trace.append((first_epoch + i, value, misses, first_epoch + best_index, decision))
        if misses >= patience:
            stop_index = i
            break  # do not inspect or select from later supplied observations
    return first_epoch + stop_index, first_epoch + best_index, trace

# Separate supplied paper logs; values are not generated by the penalty code.
main = [4, 2, 1.5, 1.6, 1.4, 1.45, 1.46, 1.3]
stop, best, observed = replay_stopping(main, patience=2)
print('main stop / selected saved epoch', stop, best)
print('observed trace: epoch, loss, misses, best epoch, action')
for row in observed:
    print(row)
